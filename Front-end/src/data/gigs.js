function generateGigsForSkill(skillSlug, categorySlug, subcategoryIds, count = 22) {
  const titles = gigTitles[skillSlug] || defaultTitles(skillSlug);
  const gigs = [];
  for (let i = 0; i < count; i++) {
    const freelancer = freelancers[i % freelancers.length];
    const price = [15, 20, 25, 30, 35, 40, 50, 60, 75, 80, 100][i % 11];
    const rating = +(4.5 + Math.random() * 0.5).toFixed(1);
    const reviews = 20 + Math.floor(Math.random() * 480);
    const deliveryDays = [1, 2, 3, 5, 7][i % 5];
    const subcategory = subcategoryIds ? subcategoryIds[i % subcategoryIds.length] : null;
    const seedId = `${skillSlug}-${i + 1}`;
    gigs.push({
      id: `${skillSlug}-${i + 1}`,
      title: titles[i % titles.length],
      price,
      rating,
      reviews,
      deliveryDays,
      freelancerName: freelancer.name,
      freelancerAvatar: freelancer.avatar,
      gigImage: `https://picsum.photos/seed/${seedId}/400/250`,
      skillSlug,
      categorySlug,
      subcategory,
    });
  }
  return gigs;
}

